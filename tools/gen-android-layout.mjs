// Generates Layout.java (the terrain layout) from assets/themes/layout.json, so the
// Java side has a single source of truth. Usage: node tools/gen-android-layout.mjs > Layout.java
import fs from 'node:fs';
const layout = JSON.parse(fs.readFileSync(new URL('../assets/themes/layout.json', import.meta.url), 'utf8'));
const ints = a => '{' + a.join(', ') + '}';
console.log(`// Generated by tools/gen-android-layout.mjs from assets/themes/layout.json. Do not edit.
package org.coastlive.core;

public final class Layout {
    private Layout() {}
    public static final int[] ANCHORS = ${ints(layout.anchors)};
    public static final int[][] PALMS = {${layout.palms.map(ints).join(', ')}};

    public static double skyScale(String theme) {
${Object.entries(layout.skyScales).map(([k, v]) => `        if (theme.equals("${k}")) return ${v};`).join('\n')}
        return 1;
    }
}`);
